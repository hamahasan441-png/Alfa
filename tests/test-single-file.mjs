#!/usr/bin/env node
/**
 * forge — one droppable file (v133).
 *
 * Install was npm-only. `npm run build:single` now produces `dist/forge.mjs`:
 * copy that one file onto any box with node >= 20 and it is a working forge.
 * No registry, no npm, no dependencies.
 *
 * WHY IT EXTRACTS INSTEAD OF FLATTENING — and why that is not a shortcut.
 *
 * The obvious build is a bundler. It cannot work here, because this codebase
 * legitimately reads its own directory: version.js reads package.json from
 * beside itself, benchsuite spawns `node <abs path>` to time a cold import,
 * ~40 modules use `import.meta.url`, and many choose `await import("./x.js")`
 * at runtime. A flat bundle has ONE import.meta.url and no files on disk, so
 * every one of those becomes a silent lie — the artifact would start, and then
 * be subtly wrong. Extraction restores the layout the code is entitled to
 * assume, and it is still one file to move around.
 *
 * What this suite protects, in order of how much it would cost to get wrong:
 *
 *   1. The artifact RUNS, and agrees with the tree it was built from.
 *   2. Extraction is atomic — a half-written tree is never importable.
 *   3. It is idempotent and keyed to content, so a rebuild is never served a
 *      stale tree and a second run costs one marker check.
 *   4. It honours FORGE_HOME, so a test (or a sandbox) is never written into
 *      the real ~/.forge.
 */
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import { execFile } from "node:child_process"

let PASS = 0, FAIL = 0
const ok = (name, cond, extra = "") => {
  if (cond) { PASS++; console.log(`  ok   ${name}`) }
  else { FAIL++; console.log(`  FAIL ${name}${extra ? "  — " + String(extra).slice(0, 300) : ""}`) }
}
const eq = (name, got, want) =>
  ok(`${name} (got ${JSON.stringify(got)})`, JSON.stringify(got) === JSON.stringify(want), `want ${JSON.stringify(want)}`)

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..")
const DIR = fs.mkdtempSync(path.join(os.tmpdir(), "forge-single-"))
const BUILDER = path.join(ROOT, "scripts", "build-single-file.mjs")

const node = (args, { env = {}, cwd = ROOT, timeout = 180000 } = {}) => new Promise((resolve) => {
  execFile(process.execPath, args, { cwd, timeout, env: { ...process.env, NO_COLOR: "1", ...env }, maxBuffer: 32 * 1024 * 1024 },
    (err, stdout, stderr) => resolve({ code: err?.code ?? 0, err, out: String(stdout || "").trim(), errOut: String(stderr || "").trim() }))
})

console.log("== the builder produces an artifact ==")
const OUT = path.join(DIR, "forge.mjs")
{
  ok("the build script is shipped, so an installed forge can rebuild itself",
    fs.existsSync(BUILDER) && JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8")).files.includes("scripts/build-single-file.mjs"))
  const r = await node([BUILDER, "--out", OUT])
  ok("it builds", r.code === 0 && fs.existsSync(OUT), r.errOut || String(r.err?.message ?? ""))
  const size = fs.existsSync(OUT) ? fs.statSync(OUT).size : 0
  ok(`the artifact is one file, small enough to move around (${(size / 1024).toFixed(0)}KB)`,
    size > 200 * 1024 && size < 4 * 1024 * 1024, `${size} bytes`)
  const src = fs.readFileSync(OUT, "utf8")
  ok("it starts with a shebang, so it is directly executable", src.startsWith("#!/usr/bin/env node"))
  ok("it imports nothing but node builtins — zero dependencies, still",
    [...src.matchAll(/^import .*? from "([^"]+)"/gm)].every((m) => m[1].startsWith("node:")),
    [...src.matchAll(/^import .*? from "([^"]+)"/gm)].map((m) => m[1]).join(","))
  ok("it says how it was made and that it must not be edited", /Generated by scripts\/build-single-file\.mjs/.test(src))
}

console.log("== it runs, and agrees with the tree it came from ==")
{
  const home = path.join(DIR, "home-a")
  const mine = await node([OUT, "--version"], { env: { FORGE_HOME: home } })
  const theirs = await node([path.join(ROOT, "forge.js"), "--version"], { env: { FORGE_HOME: home } })
  ok("the artifact runs at all", mine.code === 0, mine.errOut)
  eq("…and reports exactly what the source tree reports", mine.out, theirs.out)
  ok("…which is a real version string", /^forge v\d+\.\d+\.\d+/.test(mine.out), mine.out)
}

console.log("== it does real work, from an unrelated directory, with a cold home ==")
{
  // --version only proves the launcher started. The decision benchmark loads
  // the agent, the tools, the governor and the completion gate — if extraction
  // dropped a module or broke a path, this is where it shows.
  const home = path.join(DIR, "home-b")
  const elsewhere = fs.mkdtempSync(path.join(os.tmpdir(), "forge-elsewhere-"))
  const r = await node([OUT, "bench", "--cases"], { env: { FORGE_HOME: home, FORGE_SECURITY_MODE: "off" }, cwd: elsewhere })
  ok("the 24-case decision benchmark runs out of the single file", /FORGE-BENCH v.*score/.test(r.out), r.out.slice(0, 200) || r.errOut.slice(0, 300))
  ok("…and passes, exactly as it does from the repo", /score 100%/.test(r.out), (r.out.match(/score[^\n]*/) ?? [""])[0])
  try { fs.rmSync(elsewhere, { recursive: true, force: true }) } catch {}
}

console.log("== extraction: atomic, idempotent, and keyed to content ==")
{
  const home = path.join(DIR, "home-c")
  const first = await node([OUT, "--version"], { env: { FORGE_HOME: home } })
  ok("first run unpacks", first.code === 0, first.errOut)
  const runtime = path.join(home, "runtime")
  const ids = fs.readdirSync(runtime)
  eq("exactly one runtime tree was created", ids.length, 1)
  ok("the build id carries the version AND a content hash — a bump alone must not reuse a stale tree",
    /^\d+\.\d+\.\d+-[0-9a-f]{16}$/.test(ids[0]), ids[0])
  const tree = path.join(runtime, ids[0])
  ok("the completion marker is written", fs.existsSync(path.join(tree, ".complete")))
  ok("the real modules are on disk, not flattened", fs.existsSync(path.join(tree, "agent.js")) && fs.existsSync(path.join(tree, "mcp.js")))
  ok("…including package.json, which version.js reads from beside itself", fs.existsSync(path.join(tree, "package.json")))
  ok("no staging directory was left behind", !fs.readdirSync(runtime).some((d) => d.includes(".tmp-")), fs.readdirSync(runtime).join(","))

  const before = fs.statSync(path.join(tree, "agent.js")).mtimeMs
  const second = await node([OUT, "--version"], { env: { FORGE_HOME: home } })
  eq("a second run produces the same answer", second.out, first.out)
  eq("…without re-unpacking", fs.statSync(path.join(tree, "agent.js")).mtimeMs, before)
  eq("…and without creating a second tree", fs.readdirSync(runtime).length, 1)

  // the marker is the gate: remove it and the next run must rebuild the tree
  // An interrupted first run leaves a tree with no marker. `rename` cannot
  // replace a non-empty directory (ENOTEMPTY), so without explicit handling
  // that box stays broken until someone deletes the tree by hand.
  fs.rmSync(path.join(tree, ".complete"))
  fs.writeFileSync(path.join(tree, "agent.js"), "// truncated by an interrupted unpack\n")
  const third = await node([OUT, "--version"], { env: { FORGE_HOME: home } })
  eq("an interrupted, marker-less tree is re-unpacked rather than left broken", third.out, first.out)
  ok("…and the marker is back", fs.existsSync(path.join(tree, ".complete")))
  ok("…and the truncated module was replaced, not kept",
    fs.readFileSync(path.join(tree, "agent.js"), "utf8").length > 1000)
}

console.log("== FORGE_HOME is honoured, so nothing writes into the real one ==")
{
  const home = path.join(DIR, "home-d")
  await node([OUT, "--version"], { env: { FORGE_HOME: home } })
  ok("the tree went where FORGE_HOME said", fs.existsSync(path.join(home, "runtime")))
  const src = fs.readFileSync(OUT, "utf8")
  ok("…and the fallback is the user's home, never the cwd", /path\.join\(os\.homedir\(\), "\.forge"\)/.test(src))
}

console.log("== concurrent first runs do not corrupt each other ==")
{
  // two cold starts at once is the ordinary case on a machine that runs forge
  // from a script; the loser of the rename must use the winner's tree
  const home = path.join(DIR, "home-e")
  const [a, b, c] = await Promise.all([
    node([OUT, "--version"], { env: { FORGE_HOME: home } }),
    node([OUT, "--version"], { env: { FORGE_HOME: home } }),
    node([OUT, "--version"], { env: { FORGE_HOME: home } }),
  ])
  ok("all three succeed", a.code === 0 && b.code === 0 && c.code === 0, [a.errOut, b.errOut, c.errOut].filter(Boolean).join(" | ").slice(0, 300))
  eq("…with the same answer", [a.out, b.out, c.out], [a.out, a.out, a.out])
  eq("…and exactly one tree", fs.readdirSync(path.join(home, "runtime")).filter((d) => !d.includes(".tmp-")).length, 1)
}

console.log("== what is deliberately NOT in the file ==")
{
  // Read the builder rather than importing it: it is a SCRIPT, so importing it
  // would run a full build (into dist/) as a side effect of a test.
  const src = fs.readFileSync(BUILDER, "utf8")
  ok("the skills corpus is excluded, and the file says why",
    /skills\//.test(src) && /11\.6MB|downloads and verifies skills at runtime/.test(src))
  ok("documentation is excluded — it does not run", /\\\.\(md\|sh\)\$/.test(src) || /md\|sh/.test(src))
  ok("package.json is force-included, because version.js reads it",
    /new Set\(\["package\.json"\]\)/.test(src))
  ok("the build refuses to produce a launcher with no CLI", /refusing to build a launcher with no CLI/.test(src))
}

try { fs.rmSync(DIR, { recursive: true, force: true }) } catch {}
console.log(`\n== single-file suite: ${PASS} passed, ${FAIL} failed ==`)
process.exit(FAIL ? 1 : 0)
