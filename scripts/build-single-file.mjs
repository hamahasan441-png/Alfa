#!/usr/bin/env node
/**
 * forge — build the whole CLI as ONE droppable file (v133).
 *
 * Install was npm-only. `dist/forge.mjs` is a single self-contained file: copy
 * it onto a box that has node >= 20 and `node forge.mjs` is a working forge.
 * No npm, no registry, no dependencies — forge has none at runtime and this
 * keeps it that way.
 *
 * WHY IT SELF-EXTRACTS RATHER THAN FLATTENS
 *
 * The obvious build is a bundler: concatenate 192 ES modules, hoist the scopes,
 * rename the collisions. It would not work here, and not because of effort —
 * because this codebase legitimately reads its own directory:
 *
 *   version.js      reads package.json from beside itself
 *   benchsuite.js   path.join(HERE, "mcp.js") — spawns node on real paths
 *   measureBootMs   imports a module in a FRESH process, by path
 *   ~40 modules     new URL("./x", import.meta.url) / import.meta.url
 *   many            await import("./x.js") chosen at runtime
 *
 * A flat bundle has one `import.meta.url` and no files on disk, so every one of
 * those becomes a silent lie. Extracting restores the layout the code is
 * entitled to assume, and the result is still ONE file to move around.
 *
 * Payload: gzipped JSON, base64. Extraction happens once per build id, into
 * <FORGE_HOME|~/.forge>/runtime/<id>, written to a temp directory and renamed
 * so a half-written tree is never importable. Later runs cost a marker check.
 *
 * NOT included: `skills/` (11.6MB of the 15.4MB shipped tree). forge downloads
 * and verifies skills at runtime and is explicitly not an offline tool, so
 * baking the corpus in would grow the file 5x to ship something the runtime
 * fetches anyway. Everything needed to RUN is in here.
 *
 * Usage:  node scripts/build-single-file.mjs [--out dist/forge.mjs] [--check]
 *         --check  builds, then proves the artifact runs and matches
 */
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import zlib from "node:zlib"
import { createHash } from "node:crypto"
import { fileURLToPath } from "node:url"
import { execFileSync } from "node:child_process"

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, "..")

const argv = process.argv.slice(2)
const outArg = argv.indexOf("--out")
const OUT = path.resolve(ROOT, outArg >= 0 ? argv[outArg + 1] : "dist/forge.mjs")
const CHECK = argv.includes("--check")

/** Everything the CLI needs at runtime: the shipped file list, minus the
 *  documentation and the skills corpus, plus the manifest version.js reads. */
export function runtimeFiles(root = ROOT) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"))
  const listed = Array.isArray(pkg.files) ? pkg.files : []
  const keep = new Set(["package.json"])
  for (const f of listed) {
    if (f.endsWith("/")) continue                      // skills/ — see the header
    if (/\.(md|sh)$/i.test(f)) continue                // docs and installers do not run
    if (!fs.existsSync(path.join(root, f))) continue   // a stale entry is not fatal
    keep.add(f)
  }
  return [...keep].sort()
}

function build() {
  const files = runtimeFiles()
  const payload = {}
  for (const f of files) payload[f] = fs.readFileSync(path.join(ROOT, f), "utf8")
  if (!payload["forge.js"]) throw new Error("forge.js is not in package.json files[] — refusing to build a launcher with no CLI")

  const json = JSON.stringify(payload)
  const gz = zlib.gzipSync(Buffer.from(json, "utf8"), { level: 9 })
  const b64 = gz.toString("base64")
  const version = JSON.parse(payload["package.json"]).version
  // The build id keys the extraction directory, so it must change whenever ANY
  // byte does — a version bump alone would serve a stale tree to a rebuilt file.
  const id = `${version}-${createHash("sha256").update(json).digest("hex").slice(0, 16)}`

  const launcher = `#!/usr/bin/env node
/**
 * forge ${version} — single-file build. Generated by scripts/build-single-file.mjs.
 * Do not edit: rebuild instead. ${files.length} modules, no dependencies.
 *
 * On first run this unpacks itself into <FORGE_HOME|~/.forge>/runtime/${id}
 * and runs the CLI from there. It extracts rather than flattening because the
 * modules read their own directory (version.js reads package.json, benchsuite
 * spawns node on real paths, ~40 modules use import.meta.url) — a flat bundle
 * would make every one of those quietly wrong.
 */
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import zlib from "node:zlib"
import { pathToFileURL } from "node:url"

const BUILD_ID = ${JSON.stringify(id)}
const PAYLOAD = ${JSON.stringify(b64)}

const home = process.env.FORGE_HOME && String(process.env.FORGE_HOME).trim()
  ? path.resolve(String(process.env.FORGE_HOME))
  : path.join(os.homedir(), ".forge")
const root = path.join(home, "runtime", BUILD_ID)
const marker = path.join(root, ".complete")

if (!fs.existsSync(marker)) {
  const files = JSON.parse(zlib.gunzipSync(Buffer.from(PAYLOAD, "base64")).toString("utf8"))
  // Unpack into a sibling and RENAME: a half-written tree must never be
  // importable, and two forge processes starting at once must not interleave.
  const staging = \`\${root}.tmp-\${process.pid}-\${Date.now().toString(36)}\`
  fs.mkdirSync(staging, { recursive: true })
  for (const [rel, body] of Object.entries(files)) {
    const dest = path.join(staging, rel)
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.writeFileSync(dest, body, { mode: 0o600 })
  }
  fs.writeFileSync(path.join(staging, ".complete"), BUILD_ID)
  fs.mkdirSync(path.dirname(root), { recursive: true })
  try {
    fs.renameSync(staging, root)
  } catch {
    // Two ways to land here, and only one of them is fine:
    //   - another process won the race and its tree is the same bytes (the
    //     build id IS the content hash), so use it;
    //   - a PREVIOUS run was interrupted between mkdir and the marker, leaving
    //     a directory that rename cannot replace (ENOTEMPTY). Without this
    //     branch that box stays broken until someone deletes the tree by hand.
    if (!fs.existsSync(marker)) {
      try { fs.rmSync(root, { recursive: true, force: true }) } catch {}
      try { fs.renameSync(staging, root) } catch (e2) { if (!fs.existsSync(marker)) throw e2 }
    }
    fs.rmSync(staging, { recursive: true, force: true })
  }
}

const entry = path.join(root, "forge.js")
// forge.js only runs when it IS the entry point (it compares realpath(argv[1])
// against its own path, so that importing it in a test does not open a
// session). Pointing argv[1] at the extracted file is what makes this a CLI
// rather than a no-op — and it is also what the CLI prints in its own usage.
process.argv[1] = entry
await import(pathToFileURL(entry).href)
`

  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, launcher, { mode: 0o755 })
  return { files, out: OUT, id, version, rawBytes: Buffer.byteLength(json), outBytes: fs.statSync(OUT).size }
}

const res = build()
const kb = (n) => `${(n / 1024).toFixed(0)}KB`
console.log(`forge single-file build`)
console.log(`  ${res.files.length} modules  ${kb(res.rawBytes)} source → ${kb(res.outBytes)} packed`)
console.log(`  ${path.relative(ROOT, res.out)}   build id ${res.id}`)

if (CHECK) {
  // The only verification that means anything: run the artifact and compare it
  // against the tree it was built from.
  const home = fs.mkdtempSync(path.join(os.tmpdir(), "forge-sfb-"))
  const run = (file, args) => String(execFileSync(process.execPath, [file, ...args], {
    cwd: ROOT, env: { ...process.env, FORGE_HOME: home, NO_COLOR: "1" }, encoding: "utf8", timeout: 120000,
  })).trim()
  const want = run(path.join(ROOT, "forge.js"), ["--version"])
  const got = run(res.out, ["--version"])
  if (got !== want) { console.error(`  FAIL --version: ${JSON.stringify(got)} !== ${JSON.stringify(want)}`); process.exit(1) }
  console.log(`  ok  --version matches the source tree (${got})`)
  const again = run(res.out, ["--version"])
  if (again !== want) { console.error("  FAIL second run (extraction is not idempotent)"); process.exit(1) }
  console.log(`  ok  a second run reuses the extracted tree`)
  try { fs.rmSync(home, { recursive: true, force: true }) } catch {}
}
